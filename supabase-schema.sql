drop function if exists public.access_role(text);
create or replace function public.access_role(p_access_token text)
returns text
language sql
security definer
set search_path = public, extensions
as $$
    select role
    from public.site_access_grants
    where token_hash = encode(digest(coalesce(p_access_token, ''), 'sha256'), 'hex')
      and expires_at > now()
    limit 1;
$$;

drop function if exists public.verify_site_password(text);
create or replace function public.verify_site_password(p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    matched_role text;
    raw_token text := encode(gen_random_bytes(32), 'hex');
begin
    select role into matched_role
    from public.site_access_codes
    where enabled = true
      and password_hash = crypt(coalesce(p_password, ''), password_hash)
    limit 1;

    if matched_role is null then
        return jsonb_build_object('granted', false);
    end if;

    insert into public.site_access_grants (token_hash, role, expires_at)
    values (
        encode(digest(raw_token, 'sha256'), 'hex'),
        matched_role,
        now() + interval '30 days'
    );

    return jsonb_build_object('granted', true, 'role', matched_role, 'token', raw_token);
end;
$$;

drop function if exists public.get_recommendations(text);
create or replace function public.get_recommendations(p_access_token text)
returns setof public.recommendation_links
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
    if public.access_role(p_access_token) is null then
        raise exception '访问暗号已失效，请重新验证';
    end if;
    return query select * from public.recommendation_links order by created_at asc;
end;
$$;

drop function if exists public.get_recommendation(text, bigint);
create or replace function public.get_recommendation(p_access_token text, p_id bigint)
returns public.recommendation_links
language plpgsql
security definer
set search_path = public, extensions
as $$
declare result public.recommendation_links;
begin
    if public.access_role(p_access_token) <> 'admin' then
        raise exception '需要管理员暗号';
    end if;
    select * into result from public.recommendation_links where id = p_id;
    return result;
end;
$$;

drop function if exists public.admin_upsert_recommendation(text, bigint, text, text);
create or replace function public.admin_upsert_recommendation(
    p_access_token text,
    p_id bigint,
    p_title text,
    p_url text
)
returns public.recommendation_links
language plpgsql
security definer
set search_path = public, extensions
as $$
declare result public.recommendation_links;
begin
    if public.access_role(p_access_token) <> 'admin' then
        raise exception '需要管理员暗号';
    end if;
    if p_url !~* '^https?://' then
        raise exception '链接必须以 http:// 或 https:// 开头';
    end if;
    if p_id is null then
        insert into public.recommendation_links (title, url)
        values (trim(p_title), trim(p_url)) returning * into result;
    else
        update public.recommendation_links
        set title = trim(p_title), url = trim(p_url), updated_at = now()
        where id = p_id returning * into result;
    end if;
    return result;
end;
$$;

