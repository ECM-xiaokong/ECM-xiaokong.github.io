drop function if exists public.admin_update_normal_password(text, text);
create or replace function public.admin_update_normal_password(
    p_access_token text,
    p_new_password text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
    if public.access_role(p_access_token) <> 'admin' then
        raise exception '需要管理员暗号';
    end if;
    if char_length(coalesce(p_new_password, '')) < 6 then
        raise exception '普通暗号至少需要 6 个字符';
    end if;

    delete from public.site_access_codes where role = 'normal';
    insert into public.site_access_codes (password_hash, role)
    values (crypt(p_new_password, gen_salt('bf')), 'normal');
    return true;
end;
$$;

