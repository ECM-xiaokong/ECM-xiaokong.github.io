drop function if exists public.submit_message(text, text, text, text, text);
drop function if exists public.submit_message(text, text, text);
create or replace function public.submit_message(
    p_name text,
    p_contact text,
    p_content text,
    p_image_url text default '',
    p_link_url text default ''
)
returns public.messages
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    new_message public.messages;
    normalized_name text := trim(coalesce(p_name, ''));
    normalized_contact text := trim(coalesce(p_contact, ''));
    normalized_content text := trim(coalesce(p_content, ''));
    normalized_image_url text := trim(coalesce(p_image_url, ''));
    normalized_link_url text := trim(coalesce(p_link_url, ''));
begin
    if char_length(normalized_name) < 1 or char_length(normalized_name) > 100 then
        raise exception '姓名长度必须为 1 到 100 个字符';
    end if;

    if char_length(normalized_contact) > 200 then
        raise exception '联系方式不能超过 200 个字符';
    end if;

    if char_length(normalized_content) < 1 or char_length(normalized_content) > 600 then
        raise exception '留言长度必须为 1 到 600 个字符';
    end if;

    if normalized_link_url <> '' and normalized_link_url !~* '^https?://' then
        raise exception '留言链接必须以 http:// 或 https:// 开头';
    end if;

    if (
        select count(*)
        from public.messages
        where lower(trim(name)) = lower(normalized_name)
          and created_at > now() - interval '30 minutes'
    ) >= 3 then
        raise exception '同一个名字半小时内最多留言 3 条';
    end if;

    insert into public.messages (name, contact, content, image_url, link_url)
    values (normalized_name, normalized_contact, normalized_content, normalized_image_url, normalized_link_url)
    returning * into new_message;

    return new_message;
end;
$$;

